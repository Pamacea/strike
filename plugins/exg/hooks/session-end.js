#!/usr/bin/env node
/**
 * session-end.js - EXG Session End Hook
 * Part of Strike EXG Plugin v1.0.0
 *
 * Generates conversation summaries, script theater, and social posts
 * at the end of each Claude Code session.
 */

const fs = require('fs');
const path = require('path');

// Configuration
const EXG_DIR = '.claude/.ex-g-se';
const SESSION_ID = process.env.CLAUDE_SESSION_ID || 'unknown';
const TIMESTAMP = new Date().toISOString();

// Create output directory
const outputDir = path.join(process.cwd(), '.claude', '.ex-g-se');
if (!fs.existsSync(outputDir)) {
  fs.mkdirSync(outputDir, { recursive: true });
}

// Load style profiles
const styleProfiles = loadStyleProfiles();

// Main generation function
async function generateSessionContent() {
  console.log('📝 EXG: Generating session-end content...');

  // 1. Generate conversation summary
  const summary = await generateConversationSummary();
  fs.writeFileSync(path.join(outputDir, 'conversation.md'), summary);

  // 2. Generate script theater
  const script = await generateScriptTheater();
  fs.writeFileSync(path.join(outputDir, 'script.md'), script);

  // 3. Generate social posts
  const posts = await generateSocialPosts();
  fs.writeFileSync(path.join(outputDir, 'posts.md'), posts);

  // 4. Generate metadata
  const metadata = generateMetadata();
  fs.writeFileSync(path.join(outputDir, 'metadata.json'), JSON.stringify(metadata, null, 2));

  console.log(`✅ EXG: Content generated in ${outputDir}/`);
}

function loadStyleProfiles() {
  const dataPath = path.join(__dirname, '../data/content-reference.json');
  if (fs.existsSync(dataPath)) {
    return JSON.parse(fs.readFileSync(dataPath, 'utf8'));
  }
  return {
    styleProfiles: {
      technical: { name: 'Technical', tone: 'professional' },
      storytelling: { name: 'Storytelling', tone: 'engaging' },
      educational: { name: 'Educational', tone: 'clear' },
      opinion: { name: 'Opinion', tone: 'bold' }
    }
  };
}

