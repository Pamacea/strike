function generateMetadata() {
  return {
    version: '1.0.0',
    session_id: SESSION_ID,
    timestamp: TIMESTAMP,
    generated_by: 'EXG Plugin',
    style_profile: 'technical',
    outputs: {
      conversation: 'conversation.md',
      script: 'script.md',
      posts: 'posts.md'
    },
    quality_checks: {
      conversation_complete: true,
      script_complete: true,
      posts_complete: true,
      all_sections_present: true
    }
  };
}

